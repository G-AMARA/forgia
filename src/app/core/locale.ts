@Injectable({ providedIn: 'root' })
export class LocaleService {
  private readonly _locale = signal<Locale>('it'); // italiano di default

  readonly locale = this._locale.asReadonly();

  readonly dict = computed(() => DICTIONARY[this._locale()]);

  setLocale(locale: Locale) {
    this._locale.set(locale);
  }

  // Helper per usare nei template: t('races_title')
  t(key: string): string {
    return this.dict()[key] ?? key;
  }
}